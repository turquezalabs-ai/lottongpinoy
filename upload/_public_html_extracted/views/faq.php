            </details>

            <details class="group bg-slate-800 border border-slate-700 rounded-2xl overflow-hidden transition-all hover:border-green-500/50">
                <summary class="flex cursor-pointer items-center justify-between p-6 text-white font-bold text-lg list-none">
                    <span>What happens when there is no jackpot winner?</span>
                    <span class="text-green-400 transition group-open:rotate-180">&#9660;</span>
                </summary>
                <div class="px-6 pb-6 text-slate-400 text-sm leading-relaxed">
                    When no ticket matches all winning numbers for a particular draw, the jackpot prize "rolls over" and is added to the next draw's jackpot for the same game. This is how jackpot prizes can grow to hundreds of millions of pesos over multiple draws without a winner. The jackpot continues to accumulate until someone matches all the winning numbers. This rollover mechanism is what creates the massive jackpot amounts that generate nationwide excitement and increased ticket sales.
                </div>
            </details>

