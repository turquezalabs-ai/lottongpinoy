            <h3 class="text-lg font-bold text-slate-500 uppercase tracking-widest mt-10 mb-4">Prizes & Taxes</h3>

            <details class="group bg-slate-800 border border-slate-700 rounded-2xl overflow-hidden transition-all hover:border-green-500/50">
                <summary class="flex cursor-pointer items-center justify-between p-6 text-white font-bold text-lg list-none">
                    <span>How much is the tax on lotto winnings?</span>
                    <span class="text-green-400 transition group-open:rotate-180">&#9660;</span>
                </summary>
                <div class="px-6 pb-6 text-slate-400 text-sm leading-relaxed">
                    Under the Tax Reform for Acceleration and Inclusion (TRAIN) Law (Republic Act No. 10963), winnings above <strong class="text-white">10,000.00 pesos</strong> are subject to a <strong class="text-green-400">20% Final Withholding Tax</strong>. Prizes of 10,000 pesos and below are tax-free and can be claimed in full at any authorized PCSO outlet. The tax is automatically deducted by PCSO before the prize is released, so you receive the net amount. For example, if you win a jackpot of 100 million pesos, the 20% tax amounts to 20 million pesos, and you will receive 80 million pesos.
                </div>
            </details>

            <details class="group bg-slate-800 border border-slate-700 rounded-2xl overflow-hidden transition-all hover:border-green-500/50">
                <summary class="flex cursor-pointer items-center justify-between p-6 text-white font-bold text-lg list-none">
                    <span>Where can I claim my prize?</span>
                    <span class="text-green-400 transition group-open:rotate-180">&#9660;</span>
                </summary>
                <div class="px-6 pb-6 text-slate-400 text-sm leading-relaxed">
                    The venue for claiming your prize depends on the amount won:
                    <ul class="list-disc ml-5 space-y-2">
                        <li><strong class="text-white">20 to 5,000 pesos:</strong> Can be claimed at any authorized PCSO outlet nationwide. Simply present your winning ticket to the outlet cashier.</li>
                        <li><strong class="text-white">5,001 to 20,000 pesos:</strong> Must be claimed at any PCSO Branch Office. Bring your winning ticket and two valid IDs.</li>
                        <li><strong class="text-white">Above 20,000 pesos (including Jackpot):</strong> Must be claimed at the PCSO Main Office located at the Philippine International Convention Center (PICC) Complex, San Marcelino Street, Manila. You will need to bring your winning ticket, two valid IDs, and accomplish a claim form.</li>
                    </ul>
                    <p class="mt-3">For jackpot prizes, PCSO validates the ticket and processes the claim, which typically takes several days. The prize is paid via check issued by the Land Bank of the Philippines. See our full <a href="#" data-tab="claim" class="footer-link text-sky-400 underline">How to Claim Guide</a> for detailed requirements.</p>
                </div>
            </details>

            <details class="group bg-slate-800 border border-slate-700 rounded-2xl overflow-hidden transition-all hover:border-green-500/50">
