            <h3 class="text-lg font-bold text-slate-500 uppercase tracking-widest mt-10 mb-4">Ticket Errors & Safety</h3>

            <details class="group bg-slate-800 border border-slate-700 rounded-2xl overflow-hidden transition-all hover:border-red-500/50">
                <summary class="flex cursor-pointer items-center justify-between p-6 text-white font-bold text-lg list-none">
                    <span>What if I lost my winning ticket?</span>
                    <span class="text-red-400 transition group-open:rotate-180">&#9660;</span>
                </summary>
                <div class="px-6 pb-6 text-slate-400 text-sm leading-relaxed">
                    Unfortunately, the lotto ticket is a <strong class="text-red-400">bearer instrument</strong>. This means that whoever holds the ticket can claim the prize, regardless of who purchased it. If you lose your ticket, anyone who finds it can claim the prize. If you signed the back of the ticket when you purchased it, you may have a better chance of proving ownership at the PCSO Legal Department, but the process is difficult and not guaranteed. This is why it is extremely important to sign the back of your ticket immediately after purchase, keep it in a safe and dry place, and avoid folding, writing on, or stapling the ticket.
                </div>
            </details>

            <details class="group bg-slate-800 border border-slate-700 rounded-2xl overflow-hidden transition-all hover:border-red-500/50">
                <summary class="flex cursor-pointer items-center justify-between p-6 text-white font-bold text-lg list-none">
                    <span>What if the outlet printed the wrong numbers?</span>
                    <span class="text-red-400 transition group-open:rotate-180">&#9660;</span>
                </summary>
                <div class="px-6 pb-6 text-slate-400 text-sm leading-relaxed">
                    If the lotto outlet prints the wrong numbers on your ticket, you should immediately inform the outlet operator before leaving the counter. The operator can cancel the ticket and issue a replacement with the correct numbers. Once you leave the outlet, it becomes much more difficult to correct the error. Always check your ticket before leaving the counter to make sure the numbers, game type, and draw date are all correct. PCSO does not honor claims for tickets with errors that were not reported at the time of purchase.
                </div>
            </details>

